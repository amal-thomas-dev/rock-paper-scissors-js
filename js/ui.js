// ---------- RESULT BOX ----------

const RESULT_STYLES = {
  win: { color: '🟢', accent: '🎉', titleEmoji: '🎉🎉🎉' },
  lose: { color: '🔴', accent: '💀', titleEmoji: '💀💀💀' },
  draw: { color: '🟡', accent: '🤝', titleEmoji: '🤝🤝🤝' },
  finalWin: { color: '🟢', accent: '🏆', titleEmoji: '🎉🎉🎉' },
  finalLose: { color: '🔴', accent: '☠️', titleEmoji: '💀💀💀' },
};

function displayBox(title, detail, type) {
  const contentWidth = 44;

  const { color, accent, titleEmoji } = RESULT_STYLES[type];
  const pad = createPadder(contentWidth);
  const finalBanner =
    type === 'finalWin'
      ? '🏆🏆🏆 HUMANITY TRIUMPHS! 🏆🏆🏆'
      : type === 'finalLose'
        ? '☠️☠️☠️ THE AI HAS WON! ☠️☠️☠️'
        : null;

  if (finalBanner) {
    console.log('\n' + '═'.repeat(contentWidth));
    console.log(pad(finalBanner));
    console.log('═'.repeat(contentWidth));
  }

  const accentBar = `${color.repeat(3)} ${accent} ${color.repeat(3)}`;
  const titleLine = `${titleEmoji} ${title} ${titleEmoji}`;

  console.log(pad(accentBar));
  console.log('╔' + '═'.repeat(contentWidth) + '╗');
  console.log('║' + pad('') + '║');
  console.log('║' + pad(titleLine) + '👈👈');
  console.log('║' + pad(detail) + '║');
  console.log('║' + pad('') + '║');
  console.log('╚' + '═'.repeat(contentWidth) + '╝');
  console.log(pad(accentBar));
}

// ---------- GAME SUMMARY ----------

function displaySummary(history, playerScore, computerScore) {
  const INNER = 44;
  const cols = [6, 10, 10, 15];
  const pads = cols.map(createPadder);
  const padIn = createPadder(INNER);
  const resultLabel = {
    player: '🎉 You win',
    computer: '💀 AI wins',
    draw: '🤝 Draw',
  };

  const row = (cells) =>
    console.log('║' + cells.map((c, i) => pads[i](c)).join('│') + '║');
  const divider = '╠' + cols.map((w) => '═'.repeat(w)).join('╪') + '╣';

  console.log('\n╔' + '═'.repeat(INNER) + '╗');
  console.log('║' + padIn('📜 GAME SUMMARY 📜') + '║');
  console.log(divider);
  row(['Round', 'You', 'AI', 'Result']);
  console.log(divider);
  history.forEach((h) =>
    row([
      String(h.round),
      h.playerChoice,
      h.computerChoice,
      resultLabel[h.result],
    ]),
  );
  console.log('╠' + '═'.repeat(INNER) + '╣');
  console.log(
    '║' +
      padIn(`Final Score → You: ${playerScore} | AI: ${computerScore}`) +
      '║',
  );

  console.log('╚' + '═'.repeat(INNER) + '╝');
}

