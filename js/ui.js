// ---------- VISUAL WIDTH HELPERS ----------

// Returns the visual width of a string in a monospaced console.
function visualLength(str) {
  let len = 0;
  for (const char of str) {
    const code = char.codePointAt(0); // char is a single character, returns the code point of that char.
    // Emojis (U+1F000–U+1FFFF) are typically double‑width.
    if (code >= 0x1f000 && code <= 0x1ffff) {
      len += 2;
    } else {
      len += 1;
    }
  }
  return len;
}

// Returns a padding function for a given content width.
function createPadder(width) {
  return function (text) {
    const visualLen = visualLength(text);
    const totalPad = width - visualLen;
    const leftPad = Math.max(0, Math.floor(totalPad / 2));
    const rightPad = Math.max(0, totalPad - leftPad);
    return ' '.repeat(leftPad) + text + ' '.repeat(rightPad);
  };
}

